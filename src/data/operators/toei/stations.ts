import { nationwideRailwayId } from '../../railwayCatalogTypes.ts'

export const TOEI_SOURCE = 'https://www.kotsu.metro.tokyo.jp/subway/stations/'

function station(prefectureCode: string, slug: string, displayName: string, reading: string): Station {
  return {
    id: nationwideRailwayId.station(prefectureCode, slug),
    displayName,
    reading,
    builtIn: true,
    sourceUrl: TOEI_SOURCE,
  }
}

